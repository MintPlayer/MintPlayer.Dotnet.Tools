using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.CodeDom.Compiler;
using System.Text;

namespace MintPlayer.SourceGenerators.Tools;

public abstract class Producer
{
    /// <summary>
    /// Used when the host supplies no <c>build_property.rootnamespace</c>.
    /// </summary>
    /// <remarks>
    /// Six producers across four generator projects write <c>namespace {RootNamespace}</c>
    /// unguarded. With a null or empty value that emitted a bare <c>namespace</c> — CS1001,
    /// "Identifier expected" — so the generator silently broke the consumer's build. MSBuild
    /// always sets RootNamespace, which is why it never showed in a normal build; it bites
    /// any other host, including a plain CSharpGeneratorDriver. Normalizing here fixes every
    /// producer at once, including ones written later. A set value goes through
    /// <see cref="StringExtensions.ToSafeNamespace(string?)"/> as well, so a project named <c>My-App</c> gets
    /// <c>namespace My_App</c> rather than CS0246/CS0102/CS0548.
    /// </remarks>
    public const string DefaultRootNamespace = "GeneratedCode";

    protected Producer(string rootNamespace, string filename)
    {
        RootNamespace = rootNamespace.ToSafeNamespace() ?? DefaultRootNamespace;
        Filename = filename;
    }

    /// <summary>The <c>&lt;auto-generated&gt;</c> comment block. Write it with <c>writer.WriteLine(Header)</c>.</summary>
    /// <remarks>
    /// A raw string literal takes the line breaks of this file as it was checked out when the package was built (LF
    /// on Linux CI), while the rest of a generated file uses <see cref="Environment.NewLine"/> of the machine running
    /// the generator. The breaks are therefore normalized to <see cref="Environment.NewLine"/> here, so a Windows
    /// consumer no longer gets an LF header above a CRLF body.
    /// </remarks>
    public static readonly string Header = """
        //-----------------------------------------------------------------------------------//
        // <auto-generated>                                                                  //
        //    This code was generated from source generator.                                 //
        //                                                                                   //
        //    Manual changes to this file may cause unexpected behavior in your application. //
        //    Manual changes to this file will be overwritten if the code is regenerated.    //
        // </auto-generated>                                                                 //
        //-----------------------------------------------------------------------------------//
        """.Replace("\r\n", "\n").Replace("\n", Environment.NewLine);

    public string RootNamespace { get; }
    public string Filename { get; }

    /// <summary>
    /// When true, <see cref="Produce(SourceProductionContext)"/> writes the file preamble (<see cref="Header"/>, then
    /// <c>#nullable enable</c> when <see cref="NullableEnable"/> is true) before calling <see cref="ProduceSource"/>,
    /// and <see cref="ProduceSource"/> must not write <see cref="Header"/> itself.
    /// </summary>
    /// <remarks>
    /// Off by default, because existing producers (in this repository and in other packages built on this one)
    /// write <see cref="Header"/> themselves, and turning it on for them would write it twice. A producer opts in
    /// by overriding this to return true and deleting its own <c>writer.WriteLine(Header)</c>.
    /// When <see cref="ProduceSource"/> writes nothing, no file is added: the preamble alone is not a file.
    /// </remarks>
    protected virtual bool WritePreamble => false;

    /// <summary>
    /// Whether the preamble ends with <c>#nullable enable</c>. Only read when <see cref="WritePreamble"/> is true.
    /// </summary>
    /// <remarks>
    /// Generated code is compiled in the consumer's nullable context, which may be anything. Enabling it explicitly
    /// makes <c>?</c> annotations in the output mean the same everywhere and keeps CS8669 away. Override to return
    /// false only for output that is not nullable-correct yet.
    /// </remarks>
    protected virtual bool NullableEnable => true;

    protected abstract void ProduceSource(IndentedTextWriter writer, CancellationToken cancellationToken);

    /// <summary>Kept for source compatibility. The compilation was never used.</summary>
    [Obsolete("The compilation is not used. Call Produce(SourceProductionContext), or better, register through context.ProduceCode(...).")]
    public void Produce(SourceProductionContext context, Compilation compilation) => Produce(context);

    public void Produce(SourceProductionContext context)
    {
        context.CancellationToken.ThrowIfCancellationRequested();
        if (string.IsNullOrEmpty(Filename)) return;

        using var textWriter = new StringWriter();
        using var writer = new IndentedTextWriter(textWriter);

        try
        {
            var preambleLength = 0;
            if (WritePreamble)
            {
                writer.WriteLine(Header);
                writer.WriteLine();
                if (NullableEnable)
                {
                    writer.WriteLine("#nullable enable");
                    writer.WriteLine();
                }
                writer.Flush();
                preambleLength = textWriter.GetStringBuilder().Length;
            }

            ProduceSource(writer, context.CancellationToken);

            writer.Flush();
            var code = textWriter.ToString();
            if (code.Length > preambleLength)
                context.AddSource(Filename, SourceText.From(code, Encoding.UTF8));
        }
        catch (OperationCanceledException)
        {
            // Cancellation is not a failure; let the driver handle it.
            throw;
        }
        catch (System.Exception ex)
        {
            // This used to be `catch (System.Exception) { }`. A generator that threw
            // produced no file AND no diagnostic, so the consumer got a silent miscompile —
            // missing generated members with nothing anywhere to explain why. Reporting it
            // keeps the build alive (an unhandled exception here would take the whole
            // compilation down) while making the failure visible.
            context.ReportDiagnostic(Diagnostic.Create(ProducerFailed, Location.None, Filename, ex.GetType().Name, ex.Message));
        }
    }

    /// <summary>
    /// Reported when <see cref="ProduceSource"/> throws. Deliberately an error: a generator
    /// that cannot produce its file has broken the consumer's build in a way that is very
    /// hard to diagnose from the symptoms alone.
    /// </summary>
    public static readonly DiagnosticDescriptor ProducerFailed = new(
        id: "MPSG001",
        title: "Source generator failed to produce a file",
        messageFormat: "The source generator failed while producing '{0}': {1}: {2}",
        category: "MintPlayer.SourceGenerators",
        defaultSeverity: DiagnosticSeverity.Error,
        isEnabledByDefault: true);
}